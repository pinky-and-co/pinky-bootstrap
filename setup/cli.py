"""CLI glue — argparse + mode dispatch. See setup.py at the workspace root for usage."""

import argparse
import sys
from pathlib import Path

from . import agentic_assets, plugin_install
from .common import WORKSPACE_ROOT
from .plugin_scope import run_marketplace_wizard
from .precommit import new_repo, run_distribution
from .product_scaffold import REPO_TYPES
from .rules import distribute_all_plugin_rules, print_all_plugin_rules_report


def main(argv: list[str] | None = None) -> None:
    """Parse and dispatch. ``argv`` lets a caller (``cli_pinky.py``'s thin sub-command dispatch)
    invoke a mode programmatically without touching ``sys.argv`` — ``None`` (the CLI entry point)
    keeps today's behavior, delegating to argparse's own ``sys.argv[1:]`` default."""
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument(
        "--rules",
        nargs="?",
        const=str(WORKSPACE_ROOT),
        default=None,
        metavar="WORKSPACE",
        help="distribute each plugin's rules/<plugin>/ to the scope its plugin is installed at "
        "(default: the detected workspace root, used to resolve install scopes from). Shows the "
        "plan, asks for confirmation before applying — see --dry-run and --yes.",
    )
    # Hooks distribution
    parser.add_argument("--repo", default=None, help="distribute to a single repo")
    parser.add_argument(
        "--new-repo",
        default=None,
        metavar="NAME",
        help="create a new (pinky-*/pluto-*) repo already governed: git init + develop branch, "
        "then distribute the hooks socle. Idempotent (re-run converges).",
    )
    parser.add_argument(
        "--scaffold",
        action="store_true",
        help="with --new-repo: also lay down the docs/ Diátaxis skeleton + universal stubs "
        "(README/CONTEXT/AGENT/pyproject/LICENSE). Idempotent, one-time (not the commit-time "
        "generate-docs regeneration).",
    )
    parser.add_argument(
        "--type",
        choices=REPO_TYPES,
        default=None,
        help="with --new-repo --scaffold: which manifest to write (lib/data/web/tooling — default "
        "lib). Picks the LAYOUT only; resolve_extras() reads it back into hooks the same way it "
        "would for a hand-built repo, so this never routes hooks directly.",
    )
    parser.add_argument("--all", action="store_true", help="distribute to all repos")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="print actions, write nothing. With --rules: print the plan and stop, never ask",
    )
    parser.add_argument(
        "--yes",
        "-y",
        action="store_true",
        help="with --rules or a distribution: apply the plan without asking for confirmation "
        "(required in a non-interactive shell — no stdin to prompt on)",
    )
    parser.add_argument(
        "--check-drift", action="store_true", help="report repo vs source drift"
    )
    parser.add_argument(
        "--doctor",
        action="store_true",
        help="check the prerequisites installed plugins assume (external binaries, local Ollama, "
        "API keys) — exits non-zero if any is missing",
    )
    parser.add_argument(
        "--fix",
        action="store_true",
        help="with --doctor: offer to `brew install` each missing binary and Ollama",
    )
    parser.add_argument(
        "--commit",
        action="store_true",
        help="after distributing, commit the distributed files in each repo",
    )
    parser.add_argument(
        "--agents-md",
        action="store_true",
        help="with --repo/--all: also (re)render the workspace AGENTS.md, the touched repo's "
        "group AGENTS.md, and seed the repo's own AGENTS.md if it has none yet",
    )
    parser.add_argument(
        "--standalone",
        action="store_true",
        help="with --agents-md --repo NAME: one-time extraction gesture — fuse the workspace's "
        "fixed sections into the repo's own AGENTS.md instead of the usual fragment (never "
        "combined with --all, and never generated by default)",
    )
    parser.add_argument(
        "--plugin",
        default=None,
        metavar="PLUGIN_ID",
        help="enable this plugin — runs the interactive scope wizard (user/project, depth, one "
        "or more targets) then enables it at each via `claude plugin install --scope project`",
    )
    parser.add_argument(
        "--marketplace",
        default=None,
        help="with --plugin: the marketplace the plugin comes from (renders as PLUGIN@MARKETPLACE "
        "in enabledPlugins)",
    )
    parser.add_argument(
        "--output-style",
        default=None,
        metavar="NAME",
        help="install this output-style — copies it to ~/.claude/output-styles/ and sets "
        "outputStyle in ~/.claude/settings.json. See `pinky install --help` for the list.",
    )
    parser.add_argument(
        "--theme",
        default=None,
        metavar="NAME",
        help="install this theme — copies it to ~/.claude/themes/ and sets theme in "
        "~/.claude/settings.json. See `pinky install --help` for the list.",
    )
    parser.add_argument(
        "--live-docs",
        action="store_true",
        help="install the live board/log viewer — bundled MkDocs tooling copied to "
        "~/.local/share/pinky/live-docs/, board mounts generated, and (macOS) a launchd agent "
        "loaded so the site is served after boot",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="with --live-docs: replace a launchd agent at the target path even if pinky did not "
        "pose it (default: refuse and leave it alone). With --plugin: delete the plugin's cache "
        "directory first so the fetch re-pulls the working tree instead of keeping a stale build "
        "(dev-only — see docs/how-to/install-plugin.md)",
    )
    parser.add_argument(
        "--plugins-reconcile",
        action="store_true",
        help="audit where every known plugin is enabled / has files / ships a status line, "
        "then write nothing (the `pinky claude-plugin list` report)",
    )
    parser.add_argument(
        "--plugins-reconcile-apply",
        action="store_true",
        help="interactive: place each plugin (user / project / uninstall / skip) and purge "
        "every enable that does not match (`pinky claude-plugin reconcile`)",
    )
    parser.add_argument(
        "--plugins-who",
        action="store_true",
        help="for every plugin install in the registry, the session transcript that ran the "
        "command (or none: a hook or a script) — the proof of who installed what "
        "(`pinky claude-plugin list --who`)",
    )
    parser.add_argument(
        "--live-docs-serve", action="store_true", help=argparse.SUPPRESS
    )
    parser.add_argument(
        "--live-docs-uninstall", action="store_true", help=argparse.SUPPRESS
    )
    parser.add_argument(
        "--live-docs-status", action="store_true", help=argparse.SUPPRESS
    )
    parser.add_argument(
        "--llm-drift",
        choices=["scan", "fix"],
        default=None,
        help="scan: report LLM drift (narrative comments, long comment blocks…) per repo · "
        "fix: apply a drift kind's fixer and report the tokens it saves per read. Covers "
        "--repo NAME, --all, or the repo holding the cwd",
    )
    parser.add_argument(
        "--kind",
        action="append",
        default=None,
        metavar="KIND",
        help="with --llm-drift: drift kind to scan or fix (repeatable) — comments, narrative, "
        "long-comment",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="with --llm-drift scan: print a JSON snapshot instead of the report",
    )
    parser.add_argument(
        "--directives",
        nargs="?",
        const="",
        default=None,
        metavar="CODE",
        help="print the inline directive to paste for an error code (E402, [type-arg], B608…), "
        "or the whole table without a code",
    )
    args, _ = parser.parse_known_args(argv)

    if args.doctor:
        from . import doctor

        raise SystemExit(1 if doctor.run_doctor(fix=args.fix) else 0)

    if args.directives is not None:
        import tool_directives

        raise SystemExit(
            tool_directives.main([args.directives] if args.directives else [])
        )

    if args.llm_drift:
        from . import llm_drift

        repos = llm_drift.select_repos(args.repo, args.all)
        raise SystemExit(
            llm_drift.run(
                args.llm_drift,
                repos,
                args.kind or [],
                dry_run=args.dry_run,
                as_json=args.json,
            )
        )

    if (
        args.live_docs
        or args.live_docs_serve
        or args.live_docs_uninstall
        or args.live_docs_status
    ):
        from . import live_docs

        if args.live_docs_serve:
            live_docs.serve()
            return
        if args.live_docs_uninstall:
            removed = live_docs.uninstall()
            print(
                "removed:\n  " + "\n  ".join(removed)
                if removed
                else "nothing pinky posed to remove"
            )
            return
        if args.live_docs_status:
            print(f"live-docs: {live_docs.status().value}")
            return
        try:
            result = live_docs.install(force=args.force)
        except live_docs.LiveDocsConflict as exc:
            print(exc, file=sys.stderr)
            raise SystemExit(1) from exc
        print(f"live-docs installed → {result.install_dir}")
        print(f"  mounts: {', '.join(result.mounts) or '(none found)'}")
        print(f"  service: {result.service}")
        if result.service != "loaded":
            print(f"  `pinky live-docs serve` to view (http://{live_docs.SERVE_ADDR})")
        return

    if args.plugins_who:
        from . import plugin_provenance

        print(plugin_provenance.format_origins(plugin_provenance.registry_origins()))
        return

    if args.plugins_reconcile or args.plugins_reconcile_apply:
        from . import plugin_reconcile

        if args.plugins_reconcile_apply:
            plugin_reconcile.apply_reconcile(WORKSPACE_ROOT)
        else:
            plugin_reconcile.print_audit_report(
                plugin_reconcile.audit_plugins(WORKSPACE_ROOT)
            )
        return

    if args.plugin is not None:
        from . import plugin_reconcile

        # Snapshot BEFORE touching anything — same discipline as apply_reconcile's own loop (audit
        # once, act, purge against the pre-action snapshot). `spec` mirrors plugin_install._spec's
        # format exactly; it stays private there, this is cheap enough not to warrant exporting it.
        label_map = plugin_reconcile.label_to_settings(WORKSPACE_ROOT)
        audit = plugin_reconcile.audit_plugins(WORKSPACE_ROOT)
        spec = plugin_reconcile.resolve_spec(args.plugin, args.marketplace, audit)
        prior_state = audit.get(spec)
        args.marketplace = args.marketplace or spec.partition("@")[2] or None

        # 0. Dev cache-bust: `claude plugin install`/`update` only ever fills an absent cache dir,
        #    so a plugin pinned at 0.1.0 can go on serving a stale build after an edit, no signal.
        #    `--force` deletes it first — a no-op on a first install (nothing cached yet).
        if args.force and plugin_install.force_refetch(args.plugin, args.marketplace):
            print(f"🧹 cache cleared for {spec} — forcing a fresh fetch")
        # 1. An always-on plugin (autodiscovery, statusline) is user scope by design — the only case
        #    where `pinky` writes there. No depth question to ask.
        if args.plugin in plugin_install.KEEP_USER_SCOPE:
            plugin_install.install_plugin_files(args.plugin, args.marketplace)
            written = plugin_install.set_status_lines(
                plugin_install.resolve_install_path(args.plugin, args.marketplace)
            )
            if written:
                print(
                    f"status line wired ({', '.join(written)}) → ~/.claude/settings.json"
                )
            print(
                f"{args.plugin} kept at user scope (always-on) → ~/.claude/settings.json"
            )
            return
        # 2. Scope first: nothing is downloaded before the user picked where it goes. A project
        #    target downloads and enables the plugin right there (`claude plugin install --scope
        #    project`); user scope is written only when the user chooses it.
        roots = run_marketplace_wizard(WORKSPACE_ROOT, args.plugin, args.marketplace)
        if roots == [Path.home()]:
            plugin_install.install_plugin_files(args.plugin, args.marketplace)
        # 3. The files are cached now, wherever they went: wire what needs them.
        install_path = plugin_install.resolve_install_path(
            args.plugin, args.marketplace
        )
        written = plugin_install.set_status_lines(install_path)
        if written:
            print(f"status line wired ({', '.join(written)}) → ~/.claude/settings.json")
        if plugin_install.ships_lsp_server(install_path):
            plugin_install.ensure_lsp_tool_enabled()

        keep = {str(Path.home())} if roots == [Path.home()] else {str(r) for r in roots}
        # Only a plugin that belongs at user scope (status line, always-on) keeps a user-scope enable
        # that predates this run: for any other one it is a leftover, offered for removal below.
        if prior_state is not None and plugin_reconcile.keeps_user_scope(prior_state):
            keep.add(str(Path.home()))
        if prior_state is not None:
            removed = plugin_reconcile.stale_labels(
                prior_state, label_map, keep=keep, include_disabled=False
            )
            if removed:
                prompt = f"Also remove {args.plugin} from: {', '.join(removed)}? [y/N] "
                confirmed = args.yes or (
                    sys.stdin.isatty() and input(prompt).strip().lower() == "y"
                )
                if confirmed:
                    plugin_reconcile.purge_other_enables(
                        spec, prior_state, label_map, keep=keep, include_disabled=False
                    )
                else:
                    print(f"left unchanged at: {', '.join(removed)}")

        print(f"enabled at: {', '.join(str(r) for r in roots)}")
        return

    if args.output_style is not None:
        try:
            target = agentic_assets.install_output_style(args.output_style)
        except ValueError as exc:
            print(exc, file=sys.stderr)
            raise SystemExit(1) from exc
        print(f"output-style {args.output_style!r} installed → {target}")
        return

    if args.theme is not None:
        try:
            target = agentic_assets.install_theme(args.theme)
        except ValueError as exc:
            print(exc, file=sys.stderr)
            raise SystemExit(1) from exc
        print(f"theme {args.theme!r} installed → {target}")
        return

    if args.rules is not None:
        workspace = Path(args.rules)
        plan = distribute_all_plugin_rules(workspace, apply=False)
        print_all_plugin_rules_report(plan)
        has_changes = any(
            report.has_changes
            for by_target in plan.values()
            for report in by_target.values()
        )
        if not has_changes or args.dry_run:
            return
        if not args.yes:
            if not sys.stdin.isatty():
                print("\nNon-interactive shell — pass --yes to apply.", file=sys.stderr)
                raise SystemExit(1)
            if input("\nApply this plan? [y/N] ").strip().lower() != "y":
                print("Cancelled.")
                return
        distribute_all_plugin_rules(workspace, apply=True)
        print("\nApplied.")
        return

    # From-zero mode: create a new repo already governed (git init + develop, then distribute).
    if args.new_repo:
        if args.type and not args.scaffold:
            print(
                "--type requires --scaffold (it picks which manifest --scaffold writes)."
            )
            raise SystemExit(1)
        new_repo(args.new_repo, args)
        return

    # Distribution mode: any distribution flag is set.
    if args.repo or args.all or args.check_drift:
        run_distribution(args)
        return

    print("pinky workspace setup — no mode flag given.")
    print(
        "Run `pinky --help` (cli_pinky.py) for the sub-command list, or pass a flag directly: "
        "--new-repo, --repo/--all (distribute), --rules (workspace rules), --check-drift."
    )
    raise SystemExit(1)
