"""CLI glue — argparse + mode dispatch. See setup.py at the workspace root for usage."""

import argparse
import sys
from pathlib import Path

from . import agentic_assets, plugin_install, style
from .common import WORKSPACE_ROOT, resolve_workspace_root
from .precommit import new_repo, run_distribution
from .product_scaffold import REPO_TYPES
from .rules import distribute_all_plugin_rules, print_all_plugin_rules_report


def _resolve_rules_dir_arg(raw: str | None) -> Path | None:
    """`--rules-dir`, expanded and resolved like `--workspace` — an explicit path is compared
    against the filesystem the same way everywhere, and a path that turns out not to exist is
    flagged rather than silently read as "no override" by `_merged_sources`."""
    if raw is None:
        return None
    resolved = Path(raw).expanduser().resolve()
    if not resolved.is_dir():
        print(
            f"--rules-dir {raw!r} ({resolved}) does not exist — no user rule will be read from it",
            file=sys.stderr,
        )
    return resolved


def main(argv: list[str] | None = None) -> None:
    """Parse and dispatch. ``argv`` lets a caller (``cli_pinky.py``'s thin sub-command dispatch)
    invoke a mode programmatically without touching ``sys.argv`` — ``None`` (the CLI entry point)
    keeps today's behavior, delegating to argparse's own ``sys.argv[1:]`` default."""
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument(
        "--rules",
        nargs="?",
        const=str(WORKSPACE_ROOT),
        default=None,
        metavar="WORKSPACE",
        help="distribute each plugin's rules/<plugin>/ to the scope its plugin is installed at "
        "(default: the detected workspace root, used to resolve install scopes from). Shows the "
        "plan, asks for confirmation before applying — see --dry-run and --yes.",
    )
    # Hooks distribution
    parser.add_argument("--repo", default=None, help="distribute to a single repo")
    parser.add_argument(
        "--new-repo",
        default=None,
        metavar="NAME",
        help="create a new (pinky-*/pluto-*) repo already governed: git init + develop branch, "
        "then distribute the hooks socle. Idempotent (re-run converges).",
    )
    parser.add_argument(
        "--scaffold",
        action="store_true",
        help="with --new-repo: also lay down the docs/ Diátaxis skeleton + universal stubs "
        "(README/CONTEXT/AGENT/pyproject/LICENSE). Idempotent, one-time (not the commit-time "
        "generate-docs regeneration).",
    )
    parser.add_argument(
        "--type",
        choices=REPO_TYPES,
        default=None,
        help="with --new-repo --scaffold: which manifest to write (lib/data/web/tooling — default "
        "lib). Picks the LAYOUT only; resolve_extras() reads it back into hooks the same way it "
        "would for a hand-built repo, so this never routes hooks directly.",
    )
    parser.add_argument("--all", action="store_true", help="distribute to all repos")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="print actions, write nothing. With --rules: print the plan and stop, never ask",
    )
    parser.add_argument(
        "--yes",
        "-y",
        action="store_true",
        help="with --rules or a distribution: apply the plan without asking for confirmation "
        "(required in a non-interactive shell — no stdin to prompt on)",
    )
    parser.add_argument(
        "--check-drift", action="store_true", help="report repo vs source drift"
    )
    parser.add_argument(
        "--doctor",
        action="store_true",
        help="check the prerequisites installed plugins assume (external binaries, local Ollama, "
        "API keys) — exits non-zero if any is missing",
    )
    parser.add_argument(
        "--fix",
        action="store_true",
        help="with --doctor: offer to `brew install` each missing binary and Ollama",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="with --doctor: also list every prerequisite that is present, by category",
    )
    parser.add_argument(
        "--commit",
        action="store_true",
        help="after distributing, commit the distributed files in each repo",
    )
    parser.add_argument(
        "--agents-md",
        action="store_true",
        help="with --repo/--all: also (re)render the workspace AGENTS.md, the touched repo's "
        "group AGENTS.md, and seed the repo's own AGENTS.md if it has none yet",
    )
    parser.add_argument(
        "--standalone",
        action="store_true",
        help="with --agents-md --repo NAME: one-time extraction gesture — fuse the workspace's "
        "fixed sections into the repo's own AGENTS.md instead of the usual fragment (never "
        "combined with --all, and never generated by default)",
    )
    parser.add_argument(
        "--plugin",
        nargs="*",
        default=None,
        metavar="PLUGIN_ID",
        help="download and enable these plugins through the plugin x target table (empty: the "
        "curated ∪ installed checkbox list) via `claude plugin install --scope "
        "project` at each chosen target",
    )
    parser.add_argument(
        "--marketplace",
        default=None,
        help="with --plugin: the marketplace every named plugin comes from (renders as "
        "PLUGIN@MARKETPLACE in enabledPlugins)",
    )
    parser.add_argument(
        "--output-style",
        default=None,
        metavar="NAME",
        help="install this output-style — copies it to ~/.claude/output-styles/ and sets "
        "outputStyle in ~/.claude/settings.json. See `pinky install --help` for the list.",
    )
    parser.add_argument(
        "--theme",
        default=None,
        metavar="NAME",
        help="install this theme — copies it to ~/.claude/themes/ and sets theme in "
        "~/.claude/settings.json. See `pinky install --help` for the list.",
    )
    parser.add_argument(
        "--live-docs",
        action="store_true",
        help="install the live board/log viewer — bundled MkDocs tooling copied to "
        "~/.local/share/pinky/live-docs/, board mounts generated, and (macOS) a launchd agent "
        "loaded so the site is served after boot",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="with --live-docs: replace a launchd agent at the target path even if pinky did not "
        "pose it (default: refuse and leave it alone). With --plugin: delete the plugin's cache "
        "directory first so the fetch re-pulls the working tree instead of keeping a stale build "
        "(dev-only — see docs/how-to/install-plugin.md)",
    )
    parser.add_argument(
        "--plugins-reconcile",
        action="store_true",
        help="audit where every known plugin is enabled / has files / ships a status line, "
        "then write nothing (the `pinky claude-plugin list` report)",
    )
    parser.add_argument(
        "--plugins-reconcile-apply",
        action="store_true",
        help="interactive: place each plugin (user / project / uninstall / skip) and purge "
        "every enable that does not match (`pinky claude-plugin reconcile`)",
    )
    parser.add_argument(
        "--plugins-refresh",
        nargs="*",
        default=None,
        metavar="PLUGIN",
        help="clear and refetch these plugins' cache, no question asked (empty: every plugin "
        "installed from a local `directory` marketplace — `pinky claude-plugin refresh`)",
    )
    parser.add_argument(
        "--plugins-who",
        action="store_true",
        help="for every plugin install in the registry, the session transcript that ran the "
        "command (or none: a hook or a script) — the proof of who installed what "
        "(`pinky claude-plugin list --who`)",
    )
    parser.add_argument(
        "--plugin-enable",
        nargs="*",
        default=None,
        metavar="PLUGIN",
        help="enable these plugins — the plugin x target table, prefilled from the current "
        "state, unless --scope replaces it (empty: the curated ∪ installed checkbox list "
        "— `pinky claude-plugin enable`)",
    )
    parser.add_argument(
        "--plugin-disable",
        nargs="*",
        default=None,
        metavar="PLUGIN",
        help="disable these plugins — same table/--scope as --plugin-enable, unchecking a cell "
        "removes that enable (empty: every currently installed plugin — `pinky "
        "claude-plugin disable`)",
    )
    parser.add_argument(
        "--scope",
        action="append",
        default=None,
        metavar="PATH",
        help="with --plugin-enable/--plugin-disable: a target (workspace-relative path, or "
        "`user`), repeatable — bypasses the table entirely",
    )
    parser.add_argument(
        "--list",
        default=None,
        metavar="PATH",
        help="with --plugin/--plugin-enable and no name: the user's curated-list override "
        "(default: ~/.claude/pinky-curated-plugins.toml)",
    )
    parser.add_argument(
        "--workspace",
        default=None,
        metavar="PATH",
        help="the workspace to act on — highest priority, above PINKY_WORKSPACE_ROOT and the "
        "nearest *.code-workspace marker",
    )
    parser.add_argument(
        "--rules-dir",
        default=None,
        metavar="PATH",
        help="the user's rules override root, applied over the shipped rules/<plugin>/ (default: "
        "~/.claude/rules) — with --rules or --plugin-enable/--plugin-disable",
    )
    parser.add_argument(
        "--live-docs-serve", action="store_true", help=argparse.SUPPRESS
    )
    parser.add_argument(
        "--live-docs-uninstall", action="store_true", help=argparse.SUPPRESS
    )
    parser.add_argument(
        "--live-docs-status", action="store_true", help=argparse.SUPPRESS
    )
    parser.add_argument(
        "--llm-drift",
        choices=["scan", "fix"],
        default=None,
        help="scan: report LLM drift (narrative comments, long comment blocks…) per repo · "
        "fix: apply a drift kind's fixer and report the tokens it saves per read. Covers "
        "--repo NAME, --all, or the repo holding the cwd",
    )
    parser.add_argument(
        "--kind",
        action="append",
        default=None,
        metavar="KIND",
        help="with --llm-drift: drift kind to scan or fix (repeatable) — comments, narrative, "
        "long-comment",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="with --llm-drift scan: print a JSON snapshot instead of the report",
    )
    parser.add_argument(
        "--directives",
        nargs="?",
        const="",
        default=None,
        metavar="CODE",
        help="print the inline directive to paste for an error code (E402, [type-arg], B608…), "
        "or the whole table without a code",
    )
    args, _ = parser.parse_known_args(argv)
    color = style.use_color()

    if args.doctor:
        from . import doctor

        raise SystemExit(
            1 if doctor.run_doctor(fix=args.fix, verbose=args.verbose) else 0
        )

    if args.directives is not None:
        import tool_directives

        raise SystemExit(
            tool_directives.main([args.directives] if args.directives else [])
        )

    if args.llm_drift:
        from . import llm_drift

        repos = llm_drift.select_repos(args.repo, args.all)
        raise SystemExit(
            llm_drift.run(
                args.llm_drift,
                repos,
                args.kind or [],
                dry_run=args.dry_run,
                as_json=args.json,
            )
        )

    if (
        args.live_docs
        or args.live_docs_serve
        or args.live_docs_uninstall
        or args.live_docs_status
    ):
        from . import live_docs

        if args.live_docs_serve:
            live_docs.serve()
            return
        if args.live_docs_uninstall:
            removed = live_docs.uninstall()
            print(live_docs.render_uninstall_report(removed, color=color))
            return
        if args.live_docs_status:
            print(live_docs.render_status_report(live_docs.status(), color=color))
            return
        try:
            result = live_docs.install(force=args.force)
        except live_docs.LiveDocsConflict as exc:
            print(exc, file=sys.stderr)
            raise SystemExit(1) from exc
        print(live_docs.render_install_report(result, color=color))
        return

    if args.plugins_refresh is not None:
        outcomes = plugin_install.refresh_plugins(
            list(args.plugins_refresh), args.marketplace
        )
        print(plugin_install.render_refresh_report(outcomes, color=color))
        if any(o.status == "failed" for o in outcomes):
            raise SystemExit(1)
        return

    if args.plugins_who:
        from . import plugin_provenance

        print(plugin_provenance.format_origins(plugin_provenance.registry_origins()))
        return

    if args.plugin_enable is not None or args.plugin_disable is not None:
        from . import plugin_curated, plugin_enable, plugin_reconcile

        action, names = (
            ("enable", list(args.plugin_enable))
            if args.plugin_enable is not None
            else ("disable", list(args.plugin_disable))
        )
        resolved = resolve_workspace_root(Path.cwd(), args.workspace)
        print(
            style.paint(
                f"Workspace: {resolved.root} (via {resolved.via})",
                style.DIM,
                color=color,
            )
        )
        # Only `disable` with no name gets the compact (checked-only) table — everything it names
        # is headed for removal, so an unchecked row is noise.
        only_checked = not names and action == "disable"
        # The curated picker (below) already qualifies each freshly picked name as
        # `<name>@<marketplace>` — `--marketplace` stays for names typed directly only, or it
        # would double up the `@`.
        run_marketplace = args.marketplace
        if not names:
            if action == "enable":
                # No name → the curated ∪ installed checkbox list, an
                # unregistered marketplace's row added (and remembered) on confirmation.
                installed_names = plugin_reconcile.enabled_plugin_names(resolved.root)
                names = plugin_curated.resolve_no_name_selection(
                    resolved.root,
                    installed_names,
                    user_path=Path(args.list) if args.list else None,
                    yes=args.yes,
                    dry_run=args.dry_run,
                    color=color,
                )
                if not names:
                    print("nothing selected")
                    return
                run_marketplace = None
            else:
                # No name → every currently installed plugin, no question asked.
                names = sorted(
                    {
                        spec.split("@", 1)[0]
                        for spec in plugin_reconcile.audit_plugins(resolved.root)
                    }
                )
                if not names:
                    print("no plugin installed — nothing to disable")
                    return
        plugin_enable.run(
            action,
            names,
            resolved.root,
            marketplace=run_marketplace,
            scope=args.scope,
            yes=args.yes,
            dry_run=args.dry_run,
            user_rules_dir=_resolve_rules_dir_arg(args.rules_dir),
            only_checked=only_checked,
            verbose=args.verbose,
        )
        return

    if args.plugins_reconcile or args.plugins_reconcile_apply:
        from . import plugin_reconcile

        if args.plugins_reconcile_apply:
            plugin_reconcile.apply_reconcile(WORKSPACE_ROOT)
        else:
            plugin_reconcile.print_audit_report(
                plugin_reconcile.audit_plugins(WORKSPACE_ROOT), color=color
            )
        return

    if args.plugin is not None:
        from . import plugin_curated, plugin_enable, plugin_reconcile

        resolved = resolve_workspace_root(Path.cwd(), args.workspace)
        print(
            style.paint(
                f"Workspace: {resolved.root} (via {resolved.via})",
                style.DIM,
                color=color,
            )
        )

        # 0. No name at all: the curated ∪ installed checkbox list —
        #    the installed set doubles as the curated list's own "already have this" signal.
        names = list(args.plugin)
        from_picker = not names
        if from_picker:
            installed_names = plugin_reconcile.enabled_plugin_names(resolved.root)
            names = plugin_curated.resolve_no_name_selection(
                resolved.root,
                installed_names,
                user_path=Path(args.list) if args.list else None,
                yes=args.yes,
                dry_run=args.dry_run,
                color=color,
            )
            if not names:
                print("nothing selected")
                return

        # A name from the curated picker is already qualified as `<name>@<marketplace>`, one per
        # curated entry — `--marketplace` must not also apply to those (it would double up the
        # `@`); it still applies, as before, to a name typed directly on the command line.
        def _bare(name: str) -> str:
            return name.partition("@")[0]

        def _marketplace_for(name: str) -> str | None:
            if from_picker:
                _, sep, mp = name.partition("@")
                return mp if sep else None
            return args.marketplace

        # `claude plugin install` only fills an absent cache dir: `--force` empties it so an edited
        # plugin pinned at 0.1.0 is re-fetched. It deletes, so never under `--dry-run`.
        if args.force and not args.dry_run:
            for name in names:
                bare, mp = _bare(name), _marketplace_for(name)
                if plugin_install.force_refetch(bare, mp):
                    spec = f"{bare}@{mp}" if mp else bare
                    print(
                        f"cache cleared for {spec} — forcing a fresh fetch",
                        file=sys.stderr,
                    )
        # An always-on plugin is user scope by design, the only case `pinky` writes there: no
        # scope table, so it stays out of the shared one below.
        keep_scope = [n for n in names if _bare(n) in plugin_install.KEEP_USER_SCOPE]
        regular = [n for n in names if _bare(n) not in plugin_install.KEEP_USER_SCOPE]
        for name in keep_scope:
            bare, mp = _bare(name), _marketplace_for(name)
            if args.dry_run:
                print(f"{bare} would be kept at user scope (always-on) — dry run")
                continue
            plugin_install.install_plugin_files(bare, mp)
            written = plugin_install.set_status_lines(
                plugin_install.resolve_install_path(bare, mp)
            )
            tick = style.paint("✓", style.GREEN, color=color)
            print(
                f"{tick} {bare} kept at user scope (always-on) → ~/.claude/settings.json"
            )
            if written:
                print(
                    style.paint(
                        f"  status line wired ({', '.join(written)})"
                        " → ~/.claude/settings.json",
                        style.DIM,
                        color=color,
                    )
                )
        if not regular:
            return
        # One plugin × target table and one plan for the whole batch; a prior enable shows up
        # pre-checked, so unchecking it is how it gets removed.
        enable_result = plugin_enable.run(
            "enable",
            regular,
            resolved.root,
            marketplace=None if from_picker else args.marketplace,
            scope=args.scope,
            yes=args.yes,
            dry_run=args.dry_run,
            user_rules_dir=_resolve_rules_dir_arg(args.rules_dir),
            verbose=args.verbose,
        )
        # Only a landed or already-matching plan has the plugin on disk to wire; "nothing to do"
        # still rewires, so a re-run after `claude plugin update` refreshes a stale path.
        if not enable_result.wire:
            return
        for name in regular:
            bare, mp = _bare(name), _marketplace_for(name)
            try:
                install_path = plugin_install.resolve_install_path(bare, mp)
            except FileNotFoundError:
                continue
            written = plugin_install.set_status_lines(install_path)
            if written:
                print(
                    style.paint(
                        f"  status line wired ({', '.join(written)})"
                        " → ~/.claude/settings.json",
                        style.DIM,
                        color=color,
                    )
                )
            if plugin_install.ships_lsp_server(install_path):
                plugin_install.ensure_lsp_tool_enabled()
        return

    if args.output_style is not None:
        try:
            target = agentic_assets.install_output_style(args.output_style)
        except ValueError as exc:
            print(exc, file=sys.stderr)
            raise SystemExit(1) from exc
        tick = style.paint("✓", style.GREEN, color=color)
        print(f"{tick} output-style {args.output_style!r} installed → {target}")
        return

    if args.theme is not None:
        try:
            target = agentic_assets.install_theme(args.theme)
        except ValueError as exc:
            print(exc, file=sys.stderr)
            raise SystemExit(1) from exc
        tick = style.paint("✓", style.GREEN, color=color)
        print(f"{tick} theme {args.theme!r} installed → {target}")
        return

    if args.rules is not None:
        workspace = Path(args.rules)
        user_rules_dir = _resolve_rules_dir_arg(args.rules_dir)
        plan = distribute_all_plugin_rules(
            workspace, apply=False, user_rules_dir=user_rules_dir
        )
        print_all_plugin_rules_report(plan, verbose=args.verbose, color=color)
        has_changes = any(
            report.has_changes
            for by_target in plan.values()
            for report in by_target.values()
        )
        if not has_changes or args.dry_run:
            return
        if not args.yes:
            if not sys.stdin.isatty():
                print("\nNon-interactive shell — pass --yes to apply.", file=sys.stderr)
                raise SystemExit(1)
            if input("\nApply this plan? [y/N] ").strip().lower() != "y":
                print("cancelled.")
                return
        distribute_all_plugin_rules(
            workspace, apply=True, user_rules_dir=user_rules_dir
        )
        print(style.paint("applied.", style.GREEN, color=color))
        return

    # From-zero mode: create a new repo already governed (git init + develop, then distribute).
    if args.new_repo:
        if args.type and not args.scaffold:
            print(
                "--type requires --scaffold (it picks which manifest --scaffold writes).",
                file=sys.stderr,
            )
            raise SystemExit(1)
        new_repo(args.new_repo, args)
        return

    # Distribution mode: any distribution flag is set.
    if args.repo or args.all or args.check_drift:
        run_distribution(args)
        return

    print("pinky workspace setup — no mode flag given.", file=sys.stderr)
    print(
        "Run `pinky --help` (cli_pinky.py) for the sub-command list, or pass a flag directly: "
        "--new-repo, --repo/--all (distribute), --rules (workspace rules), --check-drift.",
        file=sys.stderr,
    )
    raise SystemExit(1)
